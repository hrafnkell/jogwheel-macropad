# PlatformIO pre-build script: embeds config/default_layers.json and
# config/REFERENCE.txt into the firmware as C arrays (generated/embedded_files.h).
Import("env")  # noqa: F821
import os

proj = env.subst("$PROJECT_DIR")  # noqa: F821
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)

FILES = [
    ("DEFAULT_LAYERS_JSON", "config/default_layers.json"),
    ("REFERENCE_TXT", "config/REFERENCE.txt"),
]

parts = ["// Generated by tools/embed_config.py - do not edit\n#pragma once\n"]
for name, rel in FILES:
    data = open(os.path.join(proj, rel), "rb").read()
    rows = [",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
    parts.append(f"static const char {name}[] = {{\n" + ",\n".join(rows) + ",0};\n")
    parts.append(f"static const size_t {name}_LEN = {len(data)};\n")
content = "".join(parts)

out = os.path.join(out_dir, "embedded_files.h")
if not os.path.exists(out) or open(out).read() != content:  # only touch when changed
    with open(out, "w") as f:
        f.write(content)

env.Append(CPPPATH=[out_dir])  # noqa: F821
